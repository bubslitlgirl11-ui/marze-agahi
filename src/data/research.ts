export function getAllScientificArticles(): (ScientificArticle & { topicCategory: string; topicTitle: string })[] {
  const result: (ScientificArticle & { topicCategory: string; topicTitle: string })[] = []
  for (const topic of RESEARCH_TOPICS) {
    for (const art of topic.articles) {
      result.push({
        ...art,
        topicCategory: topic.category,
        topicTitle: topic.title,
      })
    }
  }
  return result
}

export function getScientificArticleBySlug(slug: string): (ScientificArticle & { topicCategory: string; topicTitle: string }) | undefined {
  const all = getAllScientificArticles()
  const decoded = decodeURIComponent(slug).toLowerCase()
  return all.find((art) => art.slug.toLowerCase() === decoded || art.slug.toLowerCase() === slug.toLowerCase())
}
